"""Hearing-date extractors must not fall through to ruling-body dates (#4682).

#4667: Santa Clara's hearing-date regex had an optional ``DATE:`` prefix and
was searched across the whole document.  When the header didn't match, it
silently returned the first long-form date in the ruling body (a date of
birth, a discovery service date) and every split ruling inherited it, so the
180-day plausibility rule dropped whole PDFs.

This module audits every California hearing-date extractor for the same
shape.  Each ``*_body_date_not_hearing_date`` test feeds body-only prose
(dates that are NOT hearing dates) with no recognisable header and asserts
the extractor returns ``None``.  Each ``*_header_date_wins`` test is the
positive control: with the header present, the header date is returned even
when a body date appears first.
"""

from __future__ import annotations

from datetime import date, datetime

import pytest
from bs4 import BeautifulSoup

from courts.ca.cc_tentatives import _cc_hearing_date_from_pdf
from courts.ca.fresno_tentatives import _fresno_hearing_date_from_text
from courts.ca.la_tentatives import _extract_header_fields
from courts.ca.oc_family_law_tentatives import _oc_fl_hearing_date_from_text
from courts.ca.oc_probate_tentatives import _probate_hearing_date_from_text
from courts.ca.riverside_tentatives import _riv_hearing_date_from_text
from courts.ca.sc_tentatives import parse_hearing_date as sc_parse_hearing_date
from courts.ca.sd_calendar import _parse_calendar_date
from courts.ca.sd_tentatives import parse_tentative_ruling
from courts.ca.ventura_tentatives import parse_event_datetime
from ingestion.extract import extract_hearing_date

pytestmark = pytest.mark.regression

# Body prose modelled on the real #4667 / #4682 false positives: a claimant's
# date of birth, discovery service dates, trust formation dates, and the SF
# Unified Family Court boilerplate ("effective January 2, 2024").
BODY_ONLY = (
    "Plaintiff, date of birth (September 13, 1972), alleges that defendant\n"
    "served responses on 03/04/2021.  The Smith Family Trust dated\n"
    "October 17 1988 is the petitioner.  Remote appearances can be made\n"
    "utilizing the ZOOM platform, effective January 2, 2024.\n"
    "On or about November 30, 2022 the parties entered into an agreement.\n"
    "The motion to compel is GRANTED.\n"
)


def _to_date(value: object) -> date | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.date()
    assert isinstance(value, date)
    return value


# ---------------------------------------------------------------------------
# ingestion.extract.extract_hearing_date — shared fallback used by the worker
# (regex_fallback phase), San Bernardino's parse_document, rebuild_db.py
# (HTML events) and reingest_from_s3.py.
# ---------------------------------------------------------------------------


class TestExtractHearingDateFallback:
    def test_extract_hearing_date_body_date_not_hearing_date(self) -> None:
        assert extract_hearing_date(BODY_ONLY) is None

    def test_extract_hearing_date_generated_comment_body_date_not_hearing_date(self) -> None:
        """SD HTML carries a generator timestamp — not a hearing date."""
        html = "<head>\n<!-- Generated by San Diego Superior Court 9/23/2026 -->\n</head>"
        assert extract_hearing_date(html) is None

    @pytest.mark.parametrize(
        ("header", "expected"),
        [
            ("Hearing Date: May 28, 2026", date(2026, 5, 28)),
            ("<b> Hearing Date: </b>  August 4, 2026", date(2026, 8, 4)),
            ("Hearing Date and Time: September 24, 2026", date(2026, 9, 24)),
            ("HEARING DATE: 09/23/2026", date(2026, 9, 23)),
            ("Tentative Rulings for March 9, 2026", date(2026, 3, 9)),
            ("TENTATIVE RULING(S) FOR February 11, 2026", date(2026, 2, 11)),
            ("TENTATIVE RULING FOR MARCH 3 & 4, 2026", date(2026, 3, 3)),
            ("Tentative Rulings\nSeptember 28, 2026", date(2026, 9, 28)),
            ("No Tentative Rulings March 2, 2026", date(2026, 3, 2)),
            ("COURT CALENDAR FOR AUGUST 13, 2026", date(2026, 8, 13)),
            ("CIVIL CALENDAR For Friday, 03/13/2026", date(2026, 3, 13)),
            ("HON. YOLANDA V. TORRES\nDate: September 28, 2026", date(2026, 9, 28)),
            ("N14\nDate: Monday, September 28, 2026", date(2026, 9, 28)),
            ("Date: 03/04/26\nCourtroom B", date(2026, 3, 4)),
        ],
    )
    def test_extract_hearing_date_header_date_wins(self, header: str, expected: date) -> None:
        # Header after body prose: the labelled date must still win over the
        # earlier body dates.
        assert extract_hearing_date(BODY_ONLY + header + "\n") == expected

    def test_extract_hearing_date_filing_date_label_body_date_not_hearing_date(self) -> None:
        """'Filing Date:' / 'Service Date:' are not hearing-date labels."""
        text = "Complaint Filing Date: 01/05/2020\nService Date: March 3, 2021\n"
        assert extract_hearing_date(text) is None


