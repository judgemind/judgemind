def test_oc_family_law_body_date_not_hearing_date() -> None:
    assert _oc_fl_hearing_date_from_text(BODY_ONLY) is None


def test_oc_family_law_empty_date_label_body_date_not_hearing_date() -> None:
    """Placeholder PDFs print 'Date:' with no value — don't grab a body date."""
    text = "TENTATIVE RULINGS\nDate:\n# Case Name TENTATIVE RULING\n" + BODY_ONLY
    assert _oc_fl_hearing_date_from_text(text) is None


def test_oc_family_law_header_date_wins() -> None:
    text = "TENTATIVE RULINGS\nDate: December 5, 2025\n" + BODY_ONLY
    assert _oc_fl_hearing_date_from_text(text) == datetime(2025, 12, 5)


def test_riverside_body_date_not_hearing_date() -> None:
    assert _riv_hearing_date_from_text(BODY_ONLY) is None


def test_riverside_header_date_wins() -> None:
    text = "Tentative Rulings for March 2, 2026\n" + BODY_ONLY
    assert _riv_hearing_date_from_text(text) == datetime(2026, 3, 2)


def test_fresno_body_date_not_hearing_date() -> None:
    assert _fresno_hearing_date_from_text(BODY_ONLY) is None


def test_fresno_header_date_wins() -> None:
    text = BODY_ONLY + "Hearing Date: March 10, 2026 (Dept. 403)\n"
    assert _fresno_hearing_date_from_text(text) == datetime(2026, 3, 10)


def test_la_body_date_not_hearing_date() -> None:
    soup = BeautifulSoup(f"<div id='speechSynthesis'><p>{BODY_ONLY}</p></div>", "lxml")
    assert _extract_header_fields(soup).hearing_date is None


def test_la_header_date_wins() -> None:
    html = (
        "<div id='speechSynthesis'><p>" + BODY_ONLY + "</p>"
        "<b>Case Number:</b> 24NNCV02551 <b>Hearing Date:</b> March 2, 2026 "
        "<b>Dept:</b> 3</div>"
    )
    soup = BeautifulSoup(html, "lxml")
    assert _extract_header_fields(soup).hearing_date == datetime(2026, 3, 2)


def test_oc_probate_body_date_not_hearing_date() -> None:
    assert _probate_hearing_date_from_text(BODY_ONLY) is None


def test_oc_probate_header_date_wins() -> None:
    text = BODY_ONLY + "Date: 03/16/2026\n"
    assert _to_date(_probate_hearing_date_from_text(text)) == date(2026, 3, 16)


def test_contra_costa_body_date_not_hearing_date() -> None:
    assert _cc_hearing_date_from_pdf(BODY_ONLY) is None


@pytest.mark.parametrize(
    ("header", "expected"),
    [
        ("HEARING DATE: 03/11/2026", datetime(2026, 3, 11)),
        ("COURT CALENDAR FOR MARCH 16, 2026", datetime(2026, 3, 16)),
    ],
)
def test_contra_costa_header_date_wins(header: str, expected: datetime) -> None:
    assert _cc_hearing_date_from_pdf(BODY_ONLY + header) == expected


def _sd_roa(desc_html: str) -> BeautifulSoup:
    return BeautifulSoup(
        "<table class='roa-table'><tbody><tr><td>1</td><td>Tentative Ruling</td>"
        f"<td>{desc_html}<div class='ruling-content'><p>{BODY_ONLY}</p></div></td>"
        "</tr></tbody></table>",
        "lxml",
    )


def test_san_diego_tentatives_body_date_not_hearing_date() -> None:
    _, hearing_date = parse_tentative_ruling(_sd_roa(""))
    assert hearing_date is None


def test_san_diego_tentatives_header_date_wins() -> None:
    _, hearing_date = parse_tentative_ruling(_sd_roa("Hearing Date: March 13, 2026"))
    assert hearing_date == datetime(2026, 3, 13)


def test_san_diego_calendar_body_date_not_hearing_date() -> None:
    html = f"<html><body><h1>CIVIL CALENDAR</h1><p>{BODY_ONLY}</p></body></html>"
    assert _parse_calendar_date(html) is None


def test_san_diego_calendar_header_date_wins() -> None:
    html = f"<h1>CIVIL CALENDAR For Friday, 03/13/2026</h1><p>{BODY_ONLY}</p>"
    assert _parse_calendar_date(html) == datetime(2026, 3, 13)


def test_ventura_body_date_not_hearing_date() -> None:
    """Ventura reads a structured event-datetime cell; a bare date isn't one."""
    assert parse_event_datetime(BODY_ONLY) is None


def test_ventura_header_date_wins() -> None:
    assert parse_event_datetime("09/24/2026 8:30 AM") == datetime(2026, 9, 24, 8, 30)


def test_santa_clara_body_date_not_hearing_date() -> None:
    """Fixed by #4667 — kept here so the audit covers every CA extractor."""
    assert sc_parse_hearing_date(BODY_ONLY) is None
